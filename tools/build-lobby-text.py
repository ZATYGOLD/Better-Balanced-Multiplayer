# Better Balanced Multiplayer - builds text/en_us/balance-lobby.xml.
#
# The Game Balance text (the UpdateText files of the modinfo's bbm-balance-game
# group) replaces the game's text in game only. This copies each replaced tag
# under LOC_BBM_LOBBY_ (LOC_X becomes LOC_BBM_LOBBY_X) for the shell, where
# ui/lobby/bbm-lobby-balance-text.js shows the copies in a multiplayer setup with
# Game Balance Multiplayer. Rerun after changing the balance text:
#
#   python tools/build-lobby-text.py          writes the file
#   python tools/build-lobby-text.py --check  exits 1 if it is out of date
#
# Copyright (C) 2026  Zatygold. SPDX-License-Identifier: GPL-3.0-or-later

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODINFO = ROOT / "zatygolds-multiplayer-balance.modinfo"
OUTPUT = ROOT / "text/en_us/balance-lobby.xml"
GROUP = "bbm-balance-game"
PREFIX = "LOC_BBM_LOBBY_"
ROW = re.compile(r'^\s*<(Replace|Row) Tag="([A-Za-z0-9_]+)"><Text>(.*)</Text></\1>\s*$')
REFERENCE = re.compile(r'(?<=[{:])(LOC_[A-Za-z0-9_]+)(?=[}\]])')
NS = {"m": "ModInfo"}


def copy_tag(tag):
  return PREFIX + tag[len("LOC_"):]


def sources():
  group = ET.parse(MODINFO).getroot().find(f".//m:ActionGroup[@id='{GROUP}']", NS)
  return [item.text.strip() for item in group.findall("m:Actions/m:UpdateText/m:Item", NS)]


def rows(path):
  text = (ROOT / path).read_text(encoding="utf-8")
  expected = len(ET.fromstring(text.encode("utf-8")).findall("EnglishText/*"))
  found = [match.group(2, 3) for match in map(ROW.match, text.splitlines()) if match]
  if len(found) != expected:
    sys.exit(f"{path}: {expected} rows, {len(found)} on single lines")
  return found


def build():
  entries = {}   # tag -> (source, text); a later file wins, as its Replace does in game
  for path in sources():
    for tag, text in rows(path):
      if tag.startswith("LOC_") and not tag.startswith("LOC_BBM_"):   # BBM's own tags replace nothing
        entries.pop(tag, None)
        entries[tag] = (path, text)
  lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<Database>",
    "\t<EnglishText>",
    "\t<!-- Generated by tools/build-lobby-text.py from the Game Balance text; do not edit. -->",
  ]
  section = None
  for tag, (path, text) in entries.items():
    if path != section:
      section = path
      lines.append(f"\t<!-- Game Balance in the multiplayer setup: {Path(path).name} -->")
    text = REFERENCE.sub(lambda m: copy_tag(m.group(1)) if m.group(1) in entries else m.group(1), text)
    lines.append(f'\t\t<Row Tag="{copy_tag(tag)}"><Text>{text}</Text></Row>')
  lines += ["\t</EnglishText>", "</Database>", ""]
  return "\r\n".join(lines).encode("utf-8")


def main():
  content = build()
  if "--check" in sys.argv[1:]:
    current = OUTPUT.read_bytes() if OUTPUT.exists() else b""
    if current != content:
      sys.exit(f"{OUTPUT.relative_to(ROOT)} is out of date")
    return
  OUTPUT.write_bytes(content)
  print(f"{OUTPUT.relative_to(ROOT)}: {content.count(b'<Row ')} rows")


if __name__ == "__main__":
  main()
